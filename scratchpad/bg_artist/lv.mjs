import puppeteer from 'puppeteer-core';
const [out, area] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new' });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('PAGEERR', e.message));
await page.setViewport({ width: 1920, height: 2148 });
await page.goto('http://localhost:8080/scratchpad/bg_artist/layers.html?area=' + area, { waitUntil: 'load' });
await page.waitForFunction('window.__done', { timeout: 120000 });
await page.screenshot({ path: out, clip: { x: 0, y: 0, width: 1920, height: 2148 } });
await browser.close();
